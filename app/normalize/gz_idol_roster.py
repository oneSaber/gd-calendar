def aliases_for(name: str) -> tuple[str, ...]:
    """取某个团的别名（含自动生成的「去掉风格后缀」短名）。"""
    out = list(ALIASES.get(name, ()))
    # 图鉴名常带英文/风格后缀（「月匙 Moon-Key」「迷光 MIRAST」），
    # 取空格前的部分作候选短名 —— 但只在长度 >= 2 时用，避免过短误匹配。
    head = name.split(" ")[0].strip()
    if head and head != name and len(head) >= 2 and head not in out:
        out.append(head)
    return tuple(out)


def to_knowledge_entries() -> list[dict]:
    """转成 `KnowledgeEntry` 的构造参数（供 artist_kb 使用）。

    ⚠️ 只返回**能被当作演出团体**的（全部都是），但 `evidence` 里写清来源，
    以便 `load_knowledge_base()` 的「必须有 evidence」闸门放行。
    """
    out = []
    for (num, name, style, debut, shows, members, rating) in ROSTER:
        out.append({
            "name": name,
            "aliases": aliases_for(name),
            "style": style,
            "debut": debut,
            "shows": shows,
            "members": members,
            "rating": rating,
            "num": num,
            "evidence": (
                f"「现役广州地偶图鉴」第 {num} 号（更新 {UPDATED_AT}，"
                f"统计截至 {shows}）；风格 {style}；舞台评级 {rating}；"
                f"来源：小红书「广州地偶图鉴」笔记《现役53团最全图鉴》"
            ),
        })
    return out


